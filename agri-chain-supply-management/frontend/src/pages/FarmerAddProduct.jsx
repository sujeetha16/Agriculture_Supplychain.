import React, { useState } from "react";
import { useNavigate } from "react-router-dom";
import Alert from "../components/Alert";
import TransactionFeedback from "../components/TransactionFeedback";
import { createProductOnChain } from "../services/blockchain";
import { createProduct } from "../services/api";
import { useWallet } from "../context/WalletContext";

export default function FarmerAddProduct() {
  const { address, connect } = useWallet();
  const [form, setForm] = useState({ name: "Organic Apples", harvestDate: new Date().toISOString().slice(0, 10) });
  const [error, setError] = useState("");
  const [hash, setHash] = useState("");
  const [productId, setProductId] = useState(null);
  const [busy, setBusy] = useState(false);
  const navigate = useNavigate();

  async function submit(e) {
    e.preventDefault();
    setError("");
    setHash("");
    try {
      if (!address) await connect();
      setBusy(true);

      const chainResult = await createProductOnChain(form.name, form.harvestDate);
      setHash(chainResult.hash);

      await createProduct({
        productId: chainResult.productId,
        name: form.name,
        harvestDate: form.harvestDate,
        farmer: address,
        txHash: chainResult.hash
      });

      setProductId(chainResult.productId);
    } catch (err) {
      setError(err.message);
    } finally {
      setBusy(false);
    }
  }

  return (
    <div className="container py-5">
      <div className="row justify-content-center">
        <div className="col-lg-7">
          <div className="card border-0 shadow-sm">
            <div className="card-body p-4">
              <h2 className="fw-bold">Add Agricultural Product</h2>
              <p className="text-secondary">The ID is generated by the blockchain counter.</p>
              <Alert message={error} />
              <form onSubmit={submit}>
                <label className="form-label">Product name</label>
                <input className="form-control mb-3" value={form.name} required
                  onChange={(e) => setForm({ ...form, name: e.target.value })} />

                <label className="form-label">Harvest date</label>
                <input type="date" className="form-control" value={form.harvestDate} required
                  onChange={(e) => setForm({ ...form, harvestDate: e.target.value })} />

                <button className="btn btn-success w-100 mt-4" disabled={busy}>
                  {busy ? "Waiting for blockchain..." : "Create Product"}
                </button>
              </form>

              <TransactionFeedback hash={hash} />

              {productId && (
                <div className="alert alert-info mt-3">
                  Product <strong>#{productId}</strong> saved to blockchain and MongoDB.
                  <button className="btn btn-sm btn-info ms-2" onClick={() => navigate(`/trace/${productId}`)}>
                    View / QR
                  </button>
                </div>
              )}
            </div>
          </div>
        </div>
      </div>
    </div>
  );
}
